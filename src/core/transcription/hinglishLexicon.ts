/**
 * Preserves the original casing style (Capitalised, ALL CAPS, or lowercase)
 * when applying a canonical spelling.
 */
const preserveCasing = (original: string, replacement: string): string => {
  if (/^[A-Z][a-z]+$/.test(original)) {
    return replacement.charAt(0).toUpperCase() + replacement.slice(1).toLowerCase();
  }
  if (/^[A-Z0-9]+$/.test(original) && original.length > 1) {
    return replacement.toUpperCase();
  }
  return replacement.toLowerCase();
};

/**
 * Normalizes a single Roman Hinglish token against the canonical dictionary.
 */
export const normalizeHinglishToken = (token: string): string => {
  if (!token) return token;

  const match = /^([^\p{L}\p{N}\p{M}]*)([\p{L}\p{N}\p{M}-]+)([^\p{L}\p{N}\p{M}]*)$/u.exec(token);
  if (!match) return token;

  const [, lead, core, trail] = match;

  const devanagariDirect =
    DEVANAGARI_HINDI_TO_ROMAN[core] ||
    DEVANAGARI_HINDI_TO_ROMAN[core.normalize('NFC')] ||
    DEVANAGARI_HINDI_TO_ROMAN[core.normalize('NFD')] ||
    DEVANAGARI_HINDI_TO_ROMAN[core.replace(/[\u093C]/g, '')];
  if (devanagariDirect) {
    return `${lead}${devanagariDirect}${trail}`;
  }

  const lower = core.toLowerCase();

  const canonical = HINGLISH_CANONICAL_SPELLINGS[lower];
  if (canonical) {
    return `${lead}${preserveCasing(core, canonical)}${trail}`;
  }

  return token;
};

/**
 * Checks whether a token is recognized in the high-frequency Hinglish lexicon.
 */
export const isHinglishWord = (word: string): boolean => {
  // \p{M} keeps Devanagari vowel signs, which are marks rather than letters
  const clean = word.toLowerCase().replace(/[^\p{L}\p{M}\p{N}]/gu, '');
  return HINGLISH_VOCABULARY.has(clean) || Boolean(HINGLISH_CANONICAL_SPELLINGS[clean]);
};

/**
 * Words in the Hinglish vocabulary that are English. They are listed there
 * because creators use them inside Hindi sentences, but they are no evidence
 * that a word is Hindi \u2014 "content" alone must not send an English video
 * through translation.
 */
const ENGLISH_IN_HINGLISH_VOCABULARY = new Set<string>([
  ...HINGLISH_CREATOR_AND_TECH,
  'actually', 'basically', 'scene', 'vibe', 'tension', 'solid', 'boss', 'sorted', 'chill', 'band',
]);

/** Every Roman spelling the Hindi dictionaries produce or accept. */
const ROMAN_HINDI_WORDS = new Set<string>(
  [
    ...[...HINGLISH_VOCABULARY].filter((word) => !ENGLISH_IN_HINGLISH_VOCABULARY.has(word)),
    ...Object.keys(HINGLISH_CANONICAL_SPELLINGS),
    ...Object.values(HINGLISH_CANONICAL_SPELLINGS),
    ...Object.values(DEVANAGARI_HINDI_TO_ROMAN),
  ].map((word) => word.toLowerCase()),
);

/**
 * True for a Roman-script word that is Hindi as far as the dictionaries know
 * ("aap", "zaroori", "jyaada"). The English matcher consults this first so it
 * never "corrects" a Hindi word into the English word it happens to resemble.
 * Words that are also everyday English ("main", "do", "the") are included:
 * the caller decides what an ambiguous word means; this only says it can be Hindi.
 */
export const isRomanHindiWord = (word: string): boolean => {
  const clean = word.toLowerCase().replace(/[^\p{L}\p{N}]/gu, '');
  return Boolean(clean) && ROMAN_HINDI_WORDS.has(clean);
};

