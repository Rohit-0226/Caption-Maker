/**
 * Checks whether a token is unambiguously Hindi (Devanagari or non-homographic Roman Hindi),
 * excluding words that are also common English words.
 */
export const isUnambiguousHindiToken = (token: string): boolean => {
  if (!token) return false;
  if (/[\u0900-\u097F]/u.test(token)) return true;
  const clean = token.toLowerCase().replace(/[^\p{L}\p{N}]/gu, '');
  if (!clean || ENGLISH_HOMOGRAPHS.has(clean) || ENGLISH_IN_HINGLISH_VOCABULARY.has(clean)) return false;
  if (Boolean(HINGLISH_CANONICAL_SPELLINGS[clean])) return true;
  return HINGLISH_VOCABULARY.has(clean);
};

